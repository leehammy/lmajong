export function openingPositions(blocks) {
  return blocks.flatMap(([z, dx, dy, ...rows]) => rows.flatMap((row, r) =>
    [...row].flatMap((cell, c) => cell === '#' ? [{ x: 2 * c + dx, y: 2 * r + dy, z }] : [])));
}
